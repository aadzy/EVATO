    from pathlib import Path
    target = Path(__file__).resolve().parent.parent / "Bangalore_Map" / "hospitals.add.xml"
    write_hospital_poi_file(target)
    print(f"Wrote {target}")
    for h in HOSPITALS:
        print(f"  {h.color_str():>15}  {h.name}")
